from ref import decode
class BW:
    def __init__(s): s.v=0; s.n=0
    def put(s, val, nb): s.v |= (val & ((1<<nb)-1)) << s.n; s.n += nb
    def bytes(s): return s.v.to_bytes(16,'little')
def px(im):  # 16 pixels in raster order
    return [im.getpixel((i%4,i//4)) for i in range(16)]
def mode1(part, eps, idxbits1=True):
    b=BW(); b.put(0b10,2); b.put(part,6)
    for ch in range(3):
        for e in range(4): b.put(eps[e][ch],6)
    b.put(0,2)
    b.put((1<<46)-1 if idxbits1 else 0, 46)
    assert b.n==128; return b.bytes()
def mode0(part, eps, idx=True):
    b=BW(); b.put(0b100,3); b.put(part,6)
    for ch in range(3):
        for e in range(6): b.put(eps[e][ch],5)
    b.put((1<<29)-1 if idx else 0, 29)
    assert b.n==128; return b.bytes()
